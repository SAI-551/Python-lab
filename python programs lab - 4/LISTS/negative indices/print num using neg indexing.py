#Given a list of 7 elements, print the last element, the second-last element, and the last 3 elements
#using negative indexing.

list=[1,2,3,4,5,6,7]
print("last element:",list[-1])
print(" second last element:",list[-2])
print("last 3 elements:",list[-3:])
                        
#output:
#last element: 7
 #second last element: 6
#last 3 elements: [5, 6, 7]
