#Task B2.1: Take two integers m and n entered by the user (use input() and int()). Print the result of
#comparing them with all six comparison operators.
a = int(input("Enter a: "))#enter a:4
b = int(input("Enter b: "))#enter b:7
print(a == b)#False
print(a != b)#True
print(a > b)#False
print(a < b)#True
print(a >= b)#False
print(a <= b)#True
