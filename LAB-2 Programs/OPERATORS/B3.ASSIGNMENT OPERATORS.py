#B3. Assignment Operators
#Operators: = , += , -= , *= , /= , //= , %= , **=
#Task B3.1: Start with a variable score = 50. Apply each assignment operator one after another (in the
#order listed above), printing the value of score after every step
score = 50
print("Initial score:", score)#50

score += 10
print("After += 10:", score)#After += 10:60

score -= 5
print("After -= 5:", score)#After -= 5:55

score *= 2
print("After *= 2:", score)#"After *= 2:110

score /= 5
print("After /= 5:", score)#After /= 5:22

score %= 7
print("After %= 7:", score)#After %= 7:1

