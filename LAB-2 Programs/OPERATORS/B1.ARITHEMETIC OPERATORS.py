#Operators: +, -, *, /, // (floor division), % (modulus), ** (exponent)
#B1. Arithmetic Operators
#Task B1.1: Take two integers a = 23 and b = 6. Write a program to compute and print the result of all
#seven arithmetic operators listed above on a and b.
a = 23
b = 6
print("addition:",a+b)#addition: 29
print("subtraction:",a-b)#subtraction: 17
print("multiplication:",a*b)#multiplication: 138
print("division:",a/b)#division: 3.8333333333333335
print("floor division:",a//b)#floor division: 3
print("modulus:",a%b)#modulus: 5
print("exponent:",a**b)#exponent: 148035889
