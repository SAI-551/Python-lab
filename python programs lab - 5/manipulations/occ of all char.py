#Replace all occurrences of a character/word with another

s = input("Enter a string: ")
old = input("Enter the character/word to replace: ")
new = input("Enter the new character/word: ")

result = s.replace(old, new)

print("Updated string:", result)

#output:
#Enter a string: manikanta
#Enter the character/word to replace: mani
#Enter the new character/word: ram
#Updated string: ramkanta

